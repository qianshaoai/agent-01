import type { KbSearchResult } from "@/lib/kb/types";

const KB_NO_RELEVANT_ANSWER = "知识库中没有找到相关资料，无法回答该问题。";
const KB_UNAVAILABLE_ANSWER = "知识库暂时不可用，无法基于知识库回答该问题。";

/**
 * RAG 注入给模型的知识库优先规则。
 * 目标：知识库相关问题优先按检索资料回答；非知识库对话保留正常聊天能力。
 */
export function buildKbStrictAnswerPrompt(chunks: KbSearchResult[]): string {
  if (chunks.length === 0) {
    return (
      "【知识库优先规则】\n" +
      "本智能体已绑定知识库，但本轮没有检索到与用户问题相关的资料。\n\n" +
      "请先判断用户问题类型：\n" +
      "① 如果用户是在询问内部事实、产品资料、制度流程、客户 / 项目 / 业务数据、专有名词或其它需要知识库支撑的问题，请直接回复：\n" +
      `「${KB_NO_RELEVANT_ANSWER}」\n` +
      "   可以简短建议用户补充关键词、换一种问法，或提供更多上下文，但不要使用训练常识冒充知识库答案。\n" +
      "② 如果用户是在寒暄、闲聊、感谢、确认、追问澄清、询问你能做什么，或提出改写 / 总结 / 润色 / 翻译 / 通用建议等不依赖知识库的任务，请按智能体自身角色正常回答。\n" +
      "③ 正常回答非知识库问题时，不要声称答案来自知识库；涉及不确定事实时，请说明需要更多资料确认。\n\n" +
      "—— 以下是本轮用户问题，请按上述规则作答 ——\n"
    );
  }

  const refBlock = chunks
    .map((c, i) => `【资料 ${i + 1}】\n${c.content}`)
    .join("\n\n");

  return (
    "【知识库优先规则】\n" +
    "你正在使用一个内部知识库。请先判断用户本轮问题是否需要依赖知识库资料回答。\n\n" +
    "一、当用户问题涉及知识库可能覆盖的内部事实、产品信息、制度流程、客户资料、项目资料、业务口径、专有名词或具体数据时：\n" +
    "1. 必须优先依据下方「资料」回答。\n" +
    "2. 资料覆盖的内容拥有最高优先级；即使与你的训练常识、世界知识或普遍认知冲突，也以资料为准。\n" +
    "3. 不要反驳、纠正或质疑资料，不要补充资料外的事实判断。\n" +
    `4. 如果「资料」不足以回答该问题，请回复：「${KB_NO_RELEVANT_ANSWER}」\n` +
    "   可以简短建议用户补充关键词、换一种问法，或提供更多上下文，但不要用常识冒充知识库答案。\n\n" +
    "二、当用户问题明显不需要知识库资料时：\n" +
    "例如寒暄、闲聊、感谢、确认、追问澄清、询问你能做什么、让你改写 / 总结 / 润色 / 翻译、一般性方法建议、情绪交流或开放式聊天，请按智能体自身角色正常回答。\n" +
    "此时可以使用通用语言能力和合理推理，但不要声称这些内容来自知识库。\n\n" +
    "三、当资料与用户问题部分相关时：\n" +
    "只使用资料中能支撑的部分回答；未覆盖的部分请明确说明“知识库资料未覆盖”，不要自行编造。\n\n" +
    "—— 资料 ——\n" +
    refBlock +
    "\n\n—— 以下是本轮用户问题，请按上述规则作答 ——\n"
  );
}

export function buildKbUnavailablePrompt(): string {
  return (
    "【知识库状态提示】\n" +
    "本智能体已绑定知识库，但本轮知识库检索暂时不可用。\n\n" +
    "如果用户问题需要依赖知识库资料，请回复：\n" +
    `「${KB_UNAVAILABLE_ANSWER}」\n\n` +
    "如果用户问题不依赖知识库资料，例如寒暄、闲聊、能力说明、文本改写、总结、翻译、通用建议或澄清追问，请按智能体自身角色正常回答，并且不要声称答案来自知识库。\n\n" +
    "—— 以下是本轮用户问题，请按上述规则作答 ——\n"
  );
}
